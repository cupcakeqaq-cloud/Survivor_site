# Regenerates playlist.js for index.html.
# It scans the one subfolder next to this script that contains .mp4 files,
# so the video folder can be renamed freely.
# ASCII-only on purpose: Windows PowerShell 5.1 misreads BOM-less UTF-8 scripts.

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path

$dir = Get-ChildItem -LiteralPath $here -Directory |
       Where-Object { @(Get-ChildItem -LiteralPath $_.FullName -Filter '*.mp4' -File).Count -gt 0 } |
       Select-Object -First 1
if (-not $dir) {
    Write-Host 'ERROR: no subfolder containing .mp4 files was found next to this script.'
    exit 1
}

$files = @([IO.Directory]::GetFiles($dir.FullName, '*.mp4') |
           ForEach-Object { [IO.Path]::GetFileName($_) })
# Same ordering as TRACKS.sort() in index.html: by UTF-16 code unit, not by locale.
[Array]::Sort($files, [StringComparer]::Ordinal)

$json = '[' + (($files | ForEach-Object { '"' + $_ + '"' }) -join ',') + ']'
$q = [char]34
$nl = [Environment]::NewLine
$text = "// auto-generated by update_playlist.ps1 - do not edit by hand$nl" +
        "var DIR = $q$($dir.Name)/$q;$nl" +
        "var TRACKS = $json;$nl"

[IO.File]::WriteAllText((Join-Path $here 'playlist.js'), $text, (New-Object Text.UTF8Encoding $false))
Write-Host "OK - $($files.Count) video(s) from '$($dir.Name)' -> playlist.js"
